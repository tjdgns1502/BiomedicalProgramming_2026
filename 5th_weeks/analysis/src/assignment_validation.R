B<-10000L; alpha<-.05
rejection_rows<-list(); power_rows<-list(); counter<-0L
for(n in c(5,10,20,50)) {
 cat("Enumeration and simulation n=",n,"\n")
 states<-expand.grid(x1=0:n,x0=0:n)
 tests<-t(vapply(seq_len(nrow(states)),function(i) {
  x<-states$x1[i];y<-states$x0[i]
  tab<-matrix(c(x,n-x,y,n-y),nrow=2,byrow=TRUE)
  if(x+y==0 || x+y==2*n) return(c(Fisher=1,Pearson=1,Yates=1))
  c(Fisher=fisher.test(tab,alternative="two.sided")$p.value,
    Pearson=suppressWarnings(chisq.test(tab,correct=FALSE)$p.value),
    Yates=suppressWarnings(chisq.test(tab,correct=TRUE)$p.value))
 },numeric(3)))
 stopifnot(all(is.finite(tests)),all(tests>=0),all(tests<=1+1e-12))
 csv(cbind(data.frame(n_per_group=n),states,as.data.frame(tests)),paste0("enumeration_n",n))
 for(p in c(.05,.2,.5)) {
  prob<-dbinom(states$x1,n,p)*dbinom(states$x0,n,p)
  stopifnot(abs(sum(prob)-1)<1e-10)
  a<-rbinom(B,n,p); b<-rbinom(B,n,p)
  ids<-1+a+(n+1)*b
  for(j in seq_len(ncol(tests))) {
   exact<-sum(prob*(tests[,j]<alpha));k<-sum(tests[ids,j]<alpha)
   ci<-wilson(k,B)
   counter<-counter+1L
   rejection_rows[[counter]]<-data.frame(n_per_group=n,null_p=p,test=colnames(tests)[j],
    exact_typeI=exact,rejections=k,B=B,MC_typeI=k/B,MCSE=sqrt((k/B)*(1-k/B)/B),
    MC_low=ci[1],MC_high=ci[2],seed=20261004,rule="two-sided p < 0.05")
  }
 }
