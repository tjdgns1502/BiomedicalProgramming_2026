wilson <- function(k,b) {
 z<-qnorm(.975);p<-k/b;den<-1+z*z/b
 c(low=(p+z*z/(2*b)-z*sqrt(p*(1-p)/b+z*z/(4*b*b)))/den,
 high=(p+z*z/(2*b)+z*sqrt(p*(1-p)/b+z*z/(4*b*b)))/den)
}
