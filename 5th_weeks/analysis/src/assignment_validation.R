   test=colnames(tests)[j],exact_power=sum(prob*(tests[,j]<alpha)),MC_power=k/B,
   MC_low=ci[1],MC_high=ci[2],MCSE=sqrt((k/B)*(1-k/B)/B),B=B)
 }
}
